#!/usr/bin/env node
// Renders packages/core/src/import-changes.js, the one table of names the root
// entry dropped in 0.15 and where they went, into docs/UPGRADING.md, between
// the import-changes markers. validateImports() and tools read the same table,
// so the docs cannot disagree with what an agent is told at runtime.
//
// It writes the number of names the root entry exports into the sentence that
// gives it (the root-count markers), and renders
// packages/devtools-mcp/tool-changes.js (the MCP tools
// 0.15 removed) into docs/UPGRADING.md and docs/MCP-DEVTOOLS.md, between the
// tool-changes markers, and writes packages/what/UPGRADING.md, the copy of
// docs/UPGRADING.md that ships in what-framework.
//
// It also writes packages/compiler/src/tables/: what-compiler's copies of the
// what-core tables it compiles by, so that it loads beside a what-core of
// another release and can say so (ERR_COMPILER_RUNTIME_MISMATCH).
//
// Usage: node scripts/generate-import-changes.mjs            write the docs
//        node scripts/generate-import-changes.mjs --check    fail if any is stale
//        node scripts/generate-import-changes.mjs --changelog print release notes

import { readFileSync, writeFileSync } from 'node:fs';
import { posix, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { IMPORT_CHANGES } from '../packages/core/src/import-changes.js';
import * as rootEntry from '../packages/core/src/index.js';
import { TOOL_CHANGES } from '../packages/devtools-mcp/tool-changes.js';

const root = resolve(import.meta.dirname, '..');
const DOC = resolve(root, 'docs/UPGRADING.md');
const START = '<!-- import-changes:start (generated by scripts/generate-import-changes.mjs; edit packages/core/src/import-changes.js) -->';
const END = '<!-- import-changes:end -->';

// what-core modules what-compiler carries. They import nothing.
const COMPILER_TABLES = ['markup-rules', 'import-changes'];

function compilerTable(name) {
  const source = readFileSync(resolve(root, `packages/core/src/${name}.js`), 'utf8');
  if (/^(?:import\b|export\b.*\bfrom\s+['"])/m.test(source)) throw new Error(`packages/core/src/${name}.js imports a module, which what-compiler's copy would not resolve`);
  return `// Generated from packages/core/src/${name}.js by scripts/generate-import-changes.mjs: edit that file, then run \`npm run docs:imports\`.\n${source}`;
}

const code = (s) => `\`${s}\``;
// A note is prose that can name a component (`<For>`), which markdown would
// otherwise read as an HTML tag.
const md = (s) => s.replace(/</g, '&lt;');
const newImport = (c) => (c.to ? code(`import { ${c.as || c.name} } from '${c.to}'`) : 'removed');

function byModule(changes) {
  const map = new Map();
  for (const c of changes) {
    if (!map.has(c.to)) map.set(c.to, []);
    map.get(c.to).push(c);
  }
  return map;
}

const ROOT_COUNT = /<!-- root-count -->\d+<!-- \/root-count -->/;

function replaceRootCount(doc) {
  if (!ROOT_COUNT.test(doc)) throw new Error('docs/UPGRADING.md has no root-count markers');
  return doc.replace(ROOT_COUNT, `<!-- root-count -->${Object.keys(rootEntry).length}<!-- /root-count -->`);
}

// The names that left the root entry, and apart from them the internal
// interfaces new in 0.15, which were never on it and are not breaking changes.
function groups() {
  const leftRoot = IMPORT_CHANGES.filter((c) => !c.neverOnRoot);
  return {
    renamed: leftRoot.filter((c) => c.to && c.as),
    removed: leftRoot.filter((c) => !c.to),
    byTarget: byModule(leftRoot.filter((c) => c.to && !c.as)),
    internal: byModule(IMPORT_CHANGES.filter((c) => c.neverOnRoot)),
  };
}

const moduleTable = (byTarget) => [...byTarget].map(([to, list]) => `| ${code(to)} | ${list.map((c) => code(c.name)).join(', ')} |`);

export function renderSection() {
  const { renamed, removed, byTarget, internal } = groups();
  const out = [START, ''];
  out.push('### Renamed', '', '| Was | Now | Why |', '|---|---|---|');
  for (const c of renamed) out.push(`| ${code(c.name)} | ${newImport(c)} | ${md(c.note)} |`);
  out.push('', '### Removed', '', '| Was | Write instead |', '|---|---|');
  for (const c of removed) out.push(`| ${code(c.name)} | ${md(c.note)} |`);
  out.push('', '### Moved', '');
  out.push('Each name below keeps its name and behaviour; only the module changed. Every `what-framework/<kit>` path has a `what-core/<kit>` twin.', '');
  out.push('| Now imported from | Names |', '|---|---|', ...moduleTable(byTarget));
  out.push('', '### New internal names', '');
  out.push('The root entry never exported these: they are new in 0.15, part of what `what-core` shares with its sibling packages and tools, and not for applications. They are listed so that importing one from the root entry is answered too.', '');
  out.push('| Imported from | Names |', '|---|---|', ...moduleTable(internal));
  out.push('', END);
  return out.join('\n');
}

export function renderChangelog() {
  const { renamed, removed, byTarget } = groups();
  const lines = [];
  for (const c of renamed) lines.push(`- **Breaking:** \`${c.name}\` is now \`${c.as}\` in \`${c.to}\`. ${md(c.note)} Migration: ${newImport(c)}.`);
  for (const c of removed) lines.push(`- **Breaking:** \`${c.name}\` was removed. Migration: ${md(c.note)}`);
  // One entry per destination and note, so each group keeps its own explanation.
  for (const [to, list] of byTarget) {
    const byNote = new Map();
    for (const c of list) byNote.set(c.note, [...(byNote.get(c.note) || []), c.name]);
    for (const [note, names] of byNote) {
      lines.push(`- **Breaking:** ${names.map((n) => `\`${n}\``).join(', ')} moved from the root entry to \`${to}\`. Migration: \`import { … } from '${to}'\`. ${md(note)}`);
    }
  }
  return lines.join('\n');
}

function replaceSection(doc) {
  const start = doc.indexOf(START);
  const end = doc.indexOf(END);
  if (start === -1 || end === -1) throw new Error(`docs/UPGRADING.md has no import-changes markers`);
  return doc.slice(0, start) + renderSection() + doc.slice(end + END.length);
}

// --- MCP tool changes --------------------------------------------------------
// One block, the same in docs/UPGRADING.md and docs/MCP-DEVTOOLS.md.

const TOOLS_START = '<!-- tool-changes:start (generated by scripts/generate-import-changes.mjs; edit packages/devtools-mcp/tool-changes.js) -->';
const TOOLS_END = '<!-- tool-changes:end -->';

/** The number of tools the server registers now, by the table: what the 0.14 server had, less the removed, plus the added. */
export function toolCount() {
  const { from, removed, added } = TOOL_CHANGES;
  return from.tools - removed.reduce((n, c) => n + c.names.length, 0) + added.length;
}

export function renderToolChanges() {
  const { from, removed, added } = TOOL_CHANGES;
  const gone = removed.reduce((n, c) => n + c.names.length, 0);
  const out = [TOOLS_START, ''];
  out.push(
    `what-devtools-mcp ${from.version} registered ${from.tools} tools. ${gone} of them are gone, ${added.map(code).join(', ')} ${added.length === 1 ? 'is' : 'are'} new, and the server now registers ${toolCount()}. ` +
    'A call to a removed tool fails with `MCP error -32602: Tool … not found`; make the call on its row instead.',
    '',
  );
  out.push('| Removed | Use instead |', '|---|---|');
  for (const c of removed) out.push(`| ${c.names.map(code).join(', ')} | ${c.use.map(code).join(', then ')}${c.note ? ` (${c.note})` : ''} |`);
  out.push('', TOOLS_END);
  return out.join('\n');
}

function replaceToolChanges(doc, path) {
  const from = doc.indexOf(TOOLS_START);
  const to = doc.indexOf(TOOLS_END);
  if (from === -1 || to === -1) throw new Error(`${path} has no tool-changes markers`);
  return doc.slice(0, from) + renderToolChanges() + doc.slice(to + TOOLS_END.length);
}

// --- The copy what-framework ships --------------------------------------------
// node_modules/what-framework/UPGRADING.md, where the shipped skill and README
// send an upgrading user. docs/ is not in the package, so every relative link
// becomes an absolute link to the repository.

const REPO = 'https://github.com/CelsianJs/what-framework/blob/main/';
const COPY_HEADER = '<!-- Generated from docs/UPGRADING.md by scripts/generate-import-changes.mjs: edit that file, then run `npm run docs:imports`. -->\n';

export function renderPackageCopy(doc) {
  // A link target with no scheme that is not an in-page anchor is relative to docs/.
  return COPY_HEADER + doc.replace(/\]\((?![a-z][a-z0-9+.-]*:|#|\/)([^)\s]+)\)/gi,
    (_, target) => `](${REPO}${posix.normalize(posix.join('docs', target))})`);
}

/** Every file this script writes, as [path relative to the repo, content]. */
export function renderAll() {
  const upgrading = replaceToolChanges(replaceSection(replaceRootCount(readFileSync(DOC, 'utf8'))), 'docs/UPGRADING.md');
  return [
    ['docs/UPGRADING.md', upgrading],
    ['docs/MCP-DEVTOOLS.md', replaceToolChanges(readFileSync(resolve(root, 'docs/MCP-DEVTOOLS.md'), 'utf8'), 'docs/MCP-DEVTOOLS.md')],
    ['packages/what/UPGRADING.md', renderPackageCopy(upgrading)],
    ...COMPILER_TABLES.map((name) => [`packages/compiler/src/tables/${name}.js`, compilerTable(name)]),
  ];
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const mode = process.argv[2];
  if (mode === '--changelog') {
    console.log(renderChangelog());
  } else {
    const current = (path) => {
      try { return readFileSync(resolve(root, path), 'utf8'); } catch { return null; }
    };
    const stale = renderAll().filter(([path, text]) => current(path) !== text);
    if (mode === '--check') {
      if (stale.length) {
        for (const [path] of stale) console.error(`[import-changes] ${path} is stale. Run \`npm run docs:imports\`.`);
        process.exit(1);
      }
      console.log(`[import-changes] OK: docs/UPGRADING.md lists all ${IMPORT_CHANGES.length} changes, the MCP tool changes match in docs/MCP-DEVTOOLS.md, packages/what/UPGRADING.md is its copy, and what-compiler's tables match what-core's.`);
    } else {
      for (const [path, text] of stale) writeFileSync(resolve(root, path), text);
      console.log(`[import-changes] wrote ${IMPORT_CHANGES.length} changes to docs/UPGRADING.md; ${stale.length ? stale.map(([path]) => path).join(', ') : 'nothing'} changed.`);
    }
  }
}
