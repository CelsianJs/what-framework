#!/usr/bin/env node
// Publish the ERROR_CODES catalogue as human-readable reference.
//
//   node scripts/generate-error-docs.mjs           # write
//   node scripts/generate-error-docs.mjs --check    # fail if the checked-in copy drifted
//
// Until now the only way to read a code's suggestion and worked example was to
// call the `what_errors` MCP tool, which means running the framework. A
// developer who hits ERR_ISR_VARY_UNRESOLVED and pastes it into a search engine
// found nothing at all. Both outputs below are DERIVED from
// `packages/core/src/errors.js`; nothing here is hand-maintained, and
// `check:error-docs` fails the build if the checked-in copies drift.

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const packagesDir = join(root, 'packages');
const check = process.argv.includes('--check');

const { ERROR_CODES } = await import(join(packagesDir, 'core/src/errors.js'));

// --- Which package raises each code ----------------------------------------
// Derived by scanning source, the same way check-error-codes.mjs does, so a
// code that moves package is re-attributed without anyone editing a list.

function sourceFiles(dir, acc = []) {
  for (const entry of readdirSync(dir)) {
    if (entry === 'node_modules' || entry === 'dist') continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) sourceFiles(full, acc);
    else if (/\.(js|jsx|mjs)$/.test(entry) && !/\.test\.js$/.test(entry)) acc.push(full);
  }
  return acc;
}

const raisedBy = new Map(); // code -> Set<package name>
for (const pkgDir of readdirSync(packagesDir)) {
  const srcDir = join(packagesDir, pkgDir, 'src');
  let files;
  try { files = sourceFiles(srcDir); } catch { continue; }
  let name = pkgDir;
  try { name = JSON.parse(readFileSync(join(packagesDir, pkgDir, 'package.json'), 'utf8')).name || pkgDir; } catch {}
  for (const file of files) {
    const text = readFileSync(file, 'utf8');
    for (const def of Object.values(ERROR_CODES)) {
      // The catalogue itself is not a raise site.
      if (file.endsWith(join('core', 'src', 'errors.js'))) continue;
      if (text.includes(`'${def.code}'`) || text.includes(`"${def.code}"`)) {
        if (!raisedBy.has(def.code)) raisedBy.set(def.code, new Set());
        raisedBy.get(def.code).add(name);
      }
    }
  }
}

// Four templates are little more than a placeholder — ERR_ACTION_FAILED's is
// literally `{{message}}`, because the useful text is the original error's.
// A one-line index built from those reads "message", so fall back to the first
// sentence of the suggestion, which always says something.
function summarize(def) {
  const filled = def.template.replace(/\{\{(\w+)\}\}/g, '$1');
  if (filled.replace(/\W/g, '').length >= 22) return def.template;
  return def.suggestion.split(/(?<=\.)\s/)[0];
}

const entries = Object.entries(ERROR_CODES)
  .map(([key, def]) => ({
    key,
    ...def,
    summary: summarize(def),
    packages: [...(raisedBy.get(def.code) || [])].sort(),
  }))
  .sort((a, b) => a.code.localeCompare(b.code));

// --- docs/ERRORS.md ---------------------------------------------------------

function markdown() {
  const errors = entries.filter(e => e.severity === 'error').length;
  const warnings = entries.length - errors;
  const out = [];
  out.push('<!-- GENERATED by scripts/generate-error-docs.mjs. Do not edit by hand. -->');
  out.push('<!-- Source of truth: packages/core/src/errors.js -->');
  out.push('');
  out.push('# Error codes');
  out.push('');
  out.push(`Every diagnostic What can raise, all ${entries.length} of them: ${errors} errors and ${warnings} warnings.`);
  out.push('');
  out.push('Each one carries a suggestion and a worked example, and the same catalogue');
  out.push('backs the `what_errors` MCP tool, so an agent debugging your app reads exactly');
  out.push('what you read here.');
  out.push('');
  out.push('| Code | Severity | What it means |');
  out.push('|---|---|---|');
  for (const e of entries) {
    const summary = e.summary.replace(/\{\{(\w+)\}\}/g, '`$1`').replace(/\|/g, '\\|');
    out.push(`| [\`${e.code}\`](#${e.code.toLowerCase().replace(/_/g, '-')}) | ${e.severity} | ${summary} |`);
  }
  out.push('');
  for (const e of entries) {
    out.push(`## ${e.code}`);
    out.push('');
    out.push(`**Severity:** ${e.severity}`);
    if (e.packages.length) out.push(`  ·  **Raised by:** ${e.packages.map(p => `\`${p}\``).join(', ')}`);
    out.push('');
    out.push(`> ${e.template}`);
    out.push('');
    out.push(e.suggestion);
    if (e.codeExample) {
      out.push('');
      out.push('```jsx');
      out.push(e.codeExample.trimEnd());
      out.push('```');
    }
    out.push('');
  }
  return `${out.join('\n').trimEnd()}\n`;
}

// --- docs-site/docs/reference/errors.html -----------------------------------

const esc = s => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');

const referenceDir = join(root, 'docs-site/docs/reference');

// Reuse a sibling page's <nav> verbatim so this page can never drift from the
// rest of the section (version badge, theme toggle, active link included).
function navBlock() {
  const sibling = readFileSync(join(referenceDir, 'batch.html'), 'utf8');
  const start = sibling.indexOf('  <nav>');
  const end = sibling.indexOf('</nav>', start) + '</nav>'.length;
  return sibling.slice(start, end);
}

const ERRORS_SIDEBAR_SECTION = `      <div class="sidebar-section">
        <div class="sidebar-title">Diagnostics</div>
        <ul class="sidebar-links">
          <li><a href="./errors.html">Error codes</a></li>
        </ul>
      </div>
`;

function sidebarFor(activeHref) {
  const sibling = readFileSync(join(referenceDir, 'batch.html'), 'utf8');
  const start = sibling.indexOf('    <aside class="sidebar">');
  const end = sibling.indexOf('</aside>', start) + '</aside>'.length;
  let aside = sibling.slice(start, end)
    .replace(/ class="active"/g, '');
  if (!aside.includes('./errors.html')) {
    aside = aside.replace('    </aside>', `${ERRORS_SIDEBAR_SECTION}    </aside>`);
  }
  return aside.replace(`href="${activeHref}"`, `href="${activeHref}" class="active"`);
}

function html() {
  const errors = entries.filter(e => e.severity === 'error').length;
  const warnings = entries.length - errors;
  const body = entries.map(e => `
          <h2 id="${esc(e.code)}">${esc(e.code)}</h2>
          <p class="subtitle">${esc(e.summary.replace(/\{\{(\w+)\}\}/g, '$1'))}</p>
          <p><span class="badge badge-${esc(e.severity)}">${esc(e.severity)}</span>${
            e.packages.length ? ` Raised by ${e.packages.map(p => `<code>${esc(p)}</code>`).join(', ')}.` : ''
          }</p>
          <p>${esc(e.suggestion)}</p>
${e.codeExample ? `<pre><code>${esc(e.codeExample.trimEnd())}</code></pre>` : ''}`).join('\n');

  const toc = entries.map(e => `            <li><a href="#${esc(e.code)}">${esc(e.code)}</a></li>`).join('\n');

  return `<!DOCTYPE html>
<!-- GENERATED by scripts/generate-error-docs.mjs. Do not edit by hand. -->
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Error codes · What Framework</title>
  <meta name="description" content="Every diagnostic the What Framework can raise, with the suggestion and worked example for each of the ${entries.length} codes.">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Inter:wght@300;400;500;600;700;800;900&family=JetBrains+Mono:wght@400;500;600&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="../styles.css">
  <script src="../../theme.js"></script>
  <script src="../copy-code.js"></script>
</head>
<body>
${navBlock()}

  <div class="layout">
${sidebarFor('./errors.html')}

    <main class="content">
      <div class="content-wrapper">
        <div class="content-inner">
          <h1>Error codes</h1>
          <p class="subtitle">Every diagnostic What can raise, all ${entries.length} of them: ${errors} errors and ${warnings} warnings.</p>

          <p>Each code carries a suggestion and a worked example. The same catalogue backs
          the <code>what_errors</code> MCP tool, so an agent debugging your app reads exactly
          what you read here.</p>

          <h2 id="all-codes">All codes</h2>
          <ul class="error-index">
${toc}
          </ul>
${body}
        </div>
      </div>
    </main>
  </div>
</body>
</html>
`;
}

// --- write or check ---------------------------------------------------------

const outputs = [
  [join(root, 'docs/ERRORS.md'), markdown()],
  [join(referenceDir, 'errors.html'), html()],
];

// Every other reference page needs the sidebar link, or the new page is
// reachable only by URL.
for (const file of readdirSync(referenceDir)) {
  if (!file.endsWith('.html') || file === 'errors.html' || file === 'index.html') continue;
  const path = join(referenceDir, file);
  const src = readFileSync(path, 'utf8');
  if (src.includes('./errors.html')) continue;
  outputs.push([path, src.replace('    </aside>', `${ERRORS_SIDEBAR_SECTION}    </aside>`)]);
}

let drifted = 0;
for (const [path, content] of outputs) {
  let current = null;
  try { current = readFileSync(path, 'utf8'); } catch {}
  if (current === content) continue;
  drifted += 1;
  if (check) {
    console.error(`[error-docs] out of date: ${path.slice(root.length + 1)}`);
  } else {
    writeFileSync(path, content);
    console.log(`[error-docs] wrote ${path.slice(root.length + 1)}`);
  }
}

if (check && drifted) {
  console.error(`[error-docs] ${drifted} file(s) drifted from ERROR_CODES. Run: npm run docs:errors`);
  process.exit(1);
}
console.log(`[error-docs] OK: ${entries.length} codes${check ? ' in sync' : ' published'}.`);
